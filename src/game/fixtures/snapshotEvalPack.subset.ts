export type SnapshotEvalSuite = 'gate' | 'warden' | 'flair';
export type SnapshotEvalExpect = 'block' | 'allow' | 'skip' | 'scrub' | 'keep';

export type SnapshotEvalSnap = {
  location: string;
  crowd: 'present' | 'none' | 'unknown';
  crowdSize: number;
  indoor: boolean;
  timeOfDay: string;
  tension: string;
  exits: string[];
  props: string[];
  present: string[];
  companions: string[];
  inventory: string[];
  openingCover: boolean;
  aloneArrival: boolean;
  weather?: string;
};

export type SnapshotEvalRow = {
  id: string;
  suite: SnapshotEvalSuite;
  expect: SnapshotEvalExpect;
  playerInput: string;
  lastGmStory: string;
  snapshot: SnapshotEvalSnap;
  /** Phrases that must remain after warden (flair / keep). */
  keepPhrases?: string[];
  /** Substring that must be gone after a scrub. */
  absentAfter?: string;
};

const snap = (
  location: string,
  extra: Partial<SnapshotEvalSnap> & Pick<
    SnapshotEvalSnap,
    'crowd' | 'crowdSize' | 'indoor' | 'inventory'
  >,
): SnapshotEvalSnap => ({
  location,
  timeOfDay: extra.timeOfDay ?? 'afternoon',
  tension: extra.tension ?? 'calm',
  exits: extra.exits ?? [],
  props: extra.props ?? [],
  present: extra.present ?? [],
  companions: extra.companions ?? [],
  openingCover: extra.openingCover ?? false,
  aloneArrival: extra.aloneArrival ?? false,
  weather: extra.weather,
  crowd: extra.crowd,
  crowdSize: extra.crowdSize,
  indoor: extra.indoor,
  inventory: extra.inventory,
});

